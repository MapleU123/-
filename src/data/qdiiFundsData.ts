// 计算全市场QDII纳指与标普500额度监控汇总统计
export function calculateQDIISummaryStats(funds: QDIIFundItem[]): QDIISummaryStats {
  const totalFundsCount = funds.length;
  const nasdaqCount = funds.filter(f => f.indexCategory === 'nasdaq' || f.indexCategory === 'tech').length;
  const sp500Count = funds.filter(f => f.indexCategory === 'sp500').length;
  const suspendedCount = funds.filter(f => f.quotaStatus === 'suspended').length;
  const strictLimitedCount = funds.filter(f => f.quotaStatus === 'ultra_strict' || f.quotaStatus === 'strict').length;
  const openCount = funds.filter(f => f.quotaStatus === 'relaxed' || f.quotaStatus === 'moderate').length;
  const etfHighPremiumCount = funds.filter(f => (f.premiumRate || 0) >= 3.0).length;

  const validLimits = funds
    .filter(f => f.dailyLimitAmount > 0 && f.dailyLimitAmount < 99999999)
    .map(f => f.dailyLimitAmount);

  const averageDailyLimit = validLimits.length > 0 
    ? Math.round(validLimits.reduce((a, b) => a + b, 0) / validLimits.length)
    : 1500;

  return {
    totalFundsCount,
    nasdaqCount,
    sp500Count,
    suspendedCount,
    strictLimitedCount,
    openCount,
    etfHighPremiumCount,
    averageDailyLimit,
    lastUpdated: '实时监控'
  };
}
