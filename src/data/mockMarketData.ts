// Generate realistic 5-tier Level 2 Order Book for any stock
export function generateMockOrderBook(currentPrice: number): Level2OrderBook {
  const tick = currentPrice > 100 ? 0.1 : 0.01;
  const bids = [];
  const asks = [];

  let totalBidVol = 0;
  let totalAskVol = 0;

  for (let i = 1; i <= 5; i++) {
    const bVol = Math.floor(1000 + Math.random() * 8000 * (6 - i));
    const aVol = Math.floor(800 + Math.random() * 7000 * (6 - i));
    totalBidVol += bVol;
    totalAskVol += aVol;

    bids.push({
      price: Number((currentPrice - i * tick).toFixed(2)),
      volume: bVol,
      percentage: 0
    });

    asks.push({
      price: Number((currentPrice + i * tick).toFixed(2)),
      volume: aVol,
      percentage: 0
    });
  }

  const maxVol = Math.max(totalBidVol, totalAskVol);
  bids.forEach(b => b.percentage = Math.min(100, Math.round((b.volume / maxVol) * 200)));
  asks.forEach(a => a.percentage = Math.min(100, Math.round((a.volume / maxVol) * 200)));

  return { bids, asks: asks.reverse() };
}
