function generateIndexTimeSeries(basePrice: number, percentChange: number, totalVol: number) {
  const points = [];
  const times = [
    '09:30', '09:45', '10:00', '10:15', '10:30', '10:45', '11:00', '11:15', '11:30',
    '13:00', '13:15', '13:30', '13:45', '14:00', '14:15', '14:30', '14:45', '15:00'
  ];
  let current = basePrice;
  const target = basePrice * (1 + percentChange / 100);
  const step = (target - basePrice) / times.length;

  for (let i = 0; i < times.length; i++) {
    const randomWiggle = (Math.random() - 0.45) * (basePrice * 0.003);
    current += step + randomWiggle;
    const vol = (totalVol / times.length) * (0.8 + Math.random() * 0.4);
    const avg = basePrice + (current - basePrice) * 0.65;
    points.push({
      time: times[i],
      price: Number(current.toFixed(2)),
      volume: Number(vol.toFixed(1)),
      avgPrice: Number(avg.toFixed(2))
    });
  }
  return points;
}

