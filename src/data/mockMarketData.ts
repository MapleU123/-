function generateSectorInflowHistory(totalInflow: number, changePercent: number) {
  const points = [];
  const times = ['09:30', '10:00', '10:30', '11:00', '11:30', '13:30', '14:00', '14:30', '15:00'];
  let currentInflow = 0;
  const step = totalInflow / times.length;
  let baseIndex = 1000;

  for (let i = 0; i < times.length; i++) {
    const wiggle = (Math.random() - 0.4) * Math.abs(totalInflow * 0.1);
    currentInflow += step + wiggle;
    baseIndex += (changePercent * 10) / times.length + (Math.random() - 0.5) * 5;
    points.push({
      time: times[i],
      netInflow: Number(currentInflow.toFixed(2)),
      indexPrice: Number(baseIndex.toFixed(1))
    });
  }
  return points;
}

